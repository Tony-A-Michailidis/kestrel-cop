  function handle(msg) {
    switch (msg.t) {
      case 'hello':
        state.settings = msg.settings; renderStatus();
        if (!map && typeof maplibregl === 'undefined') { recoverLibraries(); return; }
        if (!map) initMap(msg.settings);
        applySnapshot(msg.snapshot);
        if (msg.sitrep) renderSitrep(msg.sitrep);
        break;
      case 'tracks': for (const t of msg.items) upsertTrack(t); state.trailsDirty = true; renderCounts(); break;
      case 'events': for (const e of msg.items) state.events.set(e.uid, e); state.eventsDirty = true; renderCounts(); break;
      case 'feeds': for (const f of msg.items) state.feeds.set(f.name, f); renderFeeds(); break;
      case 'remove':
        for (const uid of msg.tracks || []) { state.tracks.delete(uid); if (state.selected === uid) closeTrackCard(); }
        for (const uid of msg.events || []) state.events.delete(uid);
        state.trailsDirty = state.eventsDirty = true; renderCounts(); break;
      case 'alert': {
        const i = state.alerts.findIndex((a) => a.id === msg.item.id);
        if (i >= 0) state.alerts[i] = msg.item;
        else {
          msg.item._fresh = true; state.alerts.push(msg.item);
          if (msg.item.severity === 'HIGH') { toast(`HIGH · ${msg.item.title}`); beep(); }
        }
        renderAlerts(); renderCounts(); break;
      }
      case 'sitrep': if (!state.sitrepStream) renderSitrep(msg.item); break;
      case 'settings': {
        const prev = state.settings; state.settings = msg.settings; renderStatus();
        const moved = !prev || prev.area.name !== msg.settings.area.name || String(prev.area.center) !== String(msg.settings.area.center) || prev.area.radius_nm !== msg.settings.area.radius_nm;
        if (moved) { toast(`Picture moved to ${msg.settings.area.name}`); if (map) goHome(); }
        break;
      }
      default: break;
    }
  }

  // ---------------------------------------------------------------- push transport
  // WebSocket first; if it never opens (proxy stripping Upgrade, server without a WS library),
  // fall back to Server-Sent Events, which carries exactly the same messages. ?transport=sse forces SSE.
  function connect() {
    const params = new URLSearchParams(location.search);
    if (params.get('transport') === 'sse' || state.transport === 'sse') return connectSse();
    const proto = location.protocol === 'https:' ? 'wss' : 'ws';
    const ws = new WebSocket(`${proto}://${location.host}/ws`);
    let opened = false;
    ws.onopen = () => { opened = true; state.wsEverOpened = true; state.wsBackoff = 1000; linkState(true, 'WebSocket connected'); };
    ws.onmessage = (ev) => { try { handle(JSON.parse(ev.data)); } catch (e) { console.error('bad message', e); } };
    ws.onclose = () => {
      linkState(false, 'Reconnecting…');
      if (!opened && !state.wsEverOpened) { state.transport = 'sse'; connectSse(); return; }
      setTimeout(connect, state.wsBackoff); state.wsBackoff = Math.min(state.wsBackoff * 2, 15000);
    };
    ws.onerror = () => ws.close();
    const ping = setInterval(() => { if (ws.readyState === 1) ws.send('ping'); else if (ws.readyState > 1) clearInterval(ping); }, 25000);
  }
  function connectSse() {
    const es = new EventSource('/api/stream');
    es.onopen = () => linkState(true, 'Connected (server-sent events)');
    es.onmessage = (ev) => { try { handle(JSON.parse(ev.data)); } catch (e) { console.error('bad message', e); } };
    es.onerror = () => linkState(false, 'Reconnecting…');   // EventSource reconnects by itself
  }
