  // ---------------------------------------------------------------- layout: resizable panels, right-panel text size
  const LAYOUT = { left: [180, 520, 248], right: [320, 960, 400], scale: [0.8, 1.8, 1] };   // [min, max, default]
  const MAP_MIN_W = 320;
  const clampTo = (v, [lo, hi, dflt]) => (typeof v === 'number' && isFinite(v) ? Math.min(hi, Math.max(lo, v)) : dflt);
  function loadLayout() {
    let saved = {};
    try { saved = JSON.parse(localStorage.getItem('kestrel-layout') || '{}') || {}; } catch (e) { /* storage blocked: defaults */ }
    return fitLayout({ left: clampTo(saved.left, LAYOUT.left), right: clampTo(saved.right, LAYOUT.right), scale: clampTo(saved.scale, LAYOUT.scale) });
  }
  function fitLayout(l) {   // the map keeps a minimum width however the window is sized
    const spare = window.innerWidth - MAP_MIN_W;
    if (l.left + l.right > spare) {
      l.right = Math.max(LAYOUT.right[0], spare - l.left);
      l.left = Math.max(LAYOUT.left[0], Math.min(l.left, spare - l.right));
    }
    return l;
  }
  function applyLayout(l, persist = true) {
    const root = document.documentElement.style;
    root.setProperty('--left-w', `${Math.round(l.left)}px`);
    root.setProperty('--right-w', `${Math.round(l.right)}px`);
    root.setProperty('--right-scale', String(l.scale));
    state.layout = l;
    if (persist) { try { localStorage.setItem('kestrel-layout', JSON.stringify(l)); } catch (e) { /* ignore */ } }
    if (map) map.resize();
  }
  function initLayout() {
    applyLayout(loadLayout(), false);
    const drag = (gutter, side) => {
      gutter.addEventListener('pointerdown', (e) => {
        e.preventDefault(); gutter.setPointerCapture(e.pointerId);
        gutter.classList.add('active'); document.body.classList.add('resizing');
        const move = (ev) => {
          const l = { ...state.layout };
          l[side] = clampTo(side === 'left' ? ev.clientX : window.innerWidth - ev.clientX, LAYOUT[side]);
          applyLayout(fitLayout(l), false);
        };
        const up = () => {
          gutter.removeEventListener('pointermove', move);
          gutter.classList.remove('active'); document.body.classList.remove('resizing');
          applyLayout(state.layout);
        };
        gutter.addEventListener('pointermove', move);
        gutter.addEventListener('pointerup', up, { once: true });
        gutter.addEventListener('pointercancel', up, { once: true });
      });
      gutter.addEventListener('dblclick', () => applyLayout(fitLayout({ ...state.layout, [side]: LAYOUT[side][2] })));
    };
    drag($('#gutter-left'), 'left');
    drag($('#gutter-right'), 'right');
    const stepScale = (d) => applyLayout({ ...state.layout, scale: Math.round(clampTo(state.layout.scale + d, LAYOUT.scale) * 10) / 10 });
    $('#font-inc').addEventListener('click', () => stepScale(0.1));
    $('#font-dec').addEventListener('click', () => stepScale(-0.1));
    window.addEventListener('resize', () => { const l = fitLayout({ ...state.layout }); if (l.left !== state.layout.left || l.right !== state.layout.right) applyLayout(l); });
  }

