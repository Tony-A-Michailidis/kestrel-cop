  function beep() {
    // two short tones for a HIGH alert; browsers only allow this after the operator has interacted with the page
    try {
      const ctx = state.audio || (state.audio = new (window.AudioContext || window.webkitAudioContext)());
      if (ctx.state !== 'running') return;
      for (const [f, t0] of [[880, 0], [1175, 0.18]]) {
        const o = ctx.createOscillator(), g = ctx.createGain();
        o.type = 'sine'; o.frequency.value = f; g.gain.value = 0.0001;
        o.connect(g); g.connect(ctx.destination);
        const t = ctx.currentTime + t0;
        g.gain.exponentialRampToValueAtTime(0.08, t + 0.02); g.gain.exponentialRampToValueAtTime(0.0001, t + 0.16);
        o.start(t); o.stop(t + 0.18);
      }
    } catch (e) { /* no audio, no problem */ }
  }

